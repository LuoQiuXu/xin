RUNS = EXPERIMENT / "runs"
TRAINED_RUN = RUNS / "amp_gradient_fix_20261112_01"
ORIGINAL_EVALUATION = TRAINED_RUN / "final_evaluation"
PUBLISHED_INDEX = EXPERIMENT / "publication_20261116/ARTIFACT_SHA256.csv"
PHASE = "reconciled-final-evaluation"


def checked_metadata(path: Path) -> dict:
    status = require_complete(path, phase="imagenet-test-metadata",
                              expected={"passed": True, "matches": TEST_ROWS, "official_test_access": True})
    report = read_json(path / "reconciliation.json")
    if (read_json(path / "config.json")["source_sha256"] != sha256_file(Path(__file__).with_name("diagnose_imagenet_test.py"))
        or not report["passed"] or report["matches"]["matched_one_to_one"] != TEST_ROWS
        or report["mapping_sha256"] != status["mapping_sha256"]):
        raise RuntimeError("The metadata reconciliation is invalid or was generated by a different source")
    return report


@contextmanager
def reconciled_imagenet_dataset(exp, archived_report, manifest_shas, mark_access):
    spec = exp.datasets["imagenet_lt"]
    root = Path(spec["root"]).resolve()
    for path in (TRAIN_MANIFEST, TEST_MANIFEST):
        if sha256_file(path) != manifest_shas[path.name]:
            raise RuntimeError(f"Accepted official manifest SHA256 mismatch: {path}")
    mark_access()
    live, _, _, matches, _ = reconcile(root, TRAIN_MANIFEST, TEST_MANIFEST)
    if not live["passed"] or any(
        live[key] != archived_report[key] for key in (
            "mapping_sha256", "train_manifest_sha256", "test_manifest_sha256", "shards",
        )
    ):
        raise RuntimeError("Live ImageNet-LT metadata differs from the approved per-image reconciliation")

    aliases = [(parquet.raw_path, official.class_id) for official, parquet in matches]
    wnids = {wnid: label for label, wnid in enumerate(live["wnid_by_official_id"])}
    with closing(ImageNetLTParquetDataset(
        root, "test", eval_transform(), expected_rows=TEST_ROWS, expected_shards=TEST_SHARDS,
        num_classes=CLASS_COUNT, shard_paths=[root / item["path"] for item in live["shards"]],
        wnid_to_id=wnids, official_entries=aliases,
    )) as dataset:
        # The existing strict loader checks exact alias/label membership. Check its
        # official row ordering against the separately reconciled physical locations.
        starts = {
            (Path(group.path).relative_to(root).as_posix(), group.row_group): (group.start, group.rows)
            for group in dataset.row_groups
        }
        physical = []
        for _, row in matches:
            start, count = starts[row.shard, row.row_group]
            if not 0 <= row.row_index < count:
                raise RuntimeError(f"Invalid physical row: {row.shard} group {row.row_group} row {row.row_index}")
            physical.append(start + row.row_index)
        targets = np.asarray([official.class_id for official, _ in matches], dtype=np.int64)
        if (len(set(physical)) != TEST_ROWS or not np.array_equal(dataset._physical_indices, physical)
            or not np.array_equal(dataset.labels, targets) or not np.all(dataset.class_counts == 50)):
            raise RuntimeError("Strict loader disagrees with the official ImageNet-LT physical row and label binding")
        yield dataset, targets


def original_artifacts(provenance: dict) -> dict[str, dict]:
    with PUBLISHED_INDEX.open(encoding="utf-8-sig", newline="") as handle:
        published = {row["file"]: row for row in csv.DictReader(handle)}
    artifacts = {}

    def add(path: Path, digest: str | None = None) -> None:
        key = path.relative_to(EXPERIMENT).as_posix()
        evidence = published[key]
        if ((digest is not None and evidence["sha256"] != digest)
            or path.stat().st_size != int(evidence["size_bytes"])):
            raise RuntimeError(f"Verified artifact differs from the archived training record: {path}")
        artifacts[key] = {"sha256": evidence["sha256"], "size_bytes": path.stat().st_size}

    for pair, entry in provenance.items():
        dataset, seed_dir = pair.split("/")
        seed = int(seed_dir.split("_", 1)[1])
        add(run_path("stage1", dataset, seed) / CHECKPOINT, entry["stage1"]["artifacts"][CHECKPOINT])
        for arm, status in entry["stage2"].items():
            add(run_path("stage2", dataset, seed, arm) / HEAD, status["artifacts"][HEAD])
        feature_dir = run_path("features", dataset, seed)
        feature_artifacts = read_json(feature_dir / "status.json")["artifacts"]
        for name in (FEATURES, LABELS):
            add(feature_dir / name, feature_artifacts[name])
    for path in sorted(ORIGINAL_EVALUATION.iterdir()):
        add(path)
    add(TRAINED_RUN / "formal_execution/status.json")
    add(TRAINED_RUN / "validation/run-formal_stderr.log")
    add(TRAINED_RUN / "FORMAL_EXECUTION_REPORT.md")
    return artifacts


def verify_original_bytes(artifacts: dict[str, dict]) -> None:
    for key, evidence in artifacts.items():
        path = EXPERIMENT / key
        if path.stat().st_size != evidence["size_bytes"] or sha256_file(path) != evidence["sha256"]:
            raise RuntimeError(f"Original training or failure artifact SHA256 mismatch: {path}")


def inference(exp, name: str, models, dataset, targets, device, out: Path, status: dict):
    batch_size = exp.protocol["stage1"]["batch_size"]
    loader = make_loader(dataset, batch_size, exp.workers, exp.seeds[0])
    keys = [(seed, arm) for seed in exp.seeds for arm in (STAGE1, *exp.arms)]
    predictions = {key: np.empty(len(targets), dtype=np.int64) for key in keys}
    for encoder, classifiers in models.values():
        encoder.to(device)
        for classifier in classifiers.values():
            classifier.to(device)
    offset = 0
    with torch.inference_mode():
        for images, labels in loader:
            stop = offset + len(labels)
            if not np.array_equal(labels.numpy(), targets[offset:stop]):
                raise RuntimeError(f"{name}: TEST loader changed the official row order at row {offset}")
            images = images.to(device, non_blocking=True)
            for seed, (encoder, classifiers) in models.items():
                features = encoder(images)
                for arm, classifier in classifiers.items():
                    logits = classifier(features)
                    if not bool(torch.isfinite(logits).all()):
                        raise RuntimeError(f"{name} seed {seed} {arm}: nonfinite test logits")
                    predictions[seed, arm][offset:stop] = logits.argmax(dim=1).cpu().numpy()
            offset = stop
            if offset % 4000 == 0:
                status["rows_scored"] = offset
                save_status(out, status)
                run_log(out, f"{name}: {offset:,}/{len(targets):,} TEST rows")
    del loader
    if offset != len(targets):
        raise RuntimeError(f"{name}: not all official TEST rows were scored")
    return predictions


def verify_model_states(models, provenance: dict, name: str) -> None:
    for seed, (encoder, classifiers) in models.items():
        entry = provenance[f"{name}/seed_{seed}"]
        expected = {STAGE1: entry["stage1"]["classifier_state_sha256"]}
        expected.update({arm: state["classifier_state_sha256"] for arm, state in entry["stage2"].items()})
        if state_dict_sha256(encoder) != entry["stage1"]["encoder_state_sha256"]:
            raise RuntimeError(f"Frozen Stage-I encoder changed during inference for {name} seed {seed}")
        if any(state_dict_sha256(module) != expected[arm] for arm, module in classifiers.items()):
            raise RuntimeError(f"A frozen classifier changed during inference for {name} seed {seed}")


def write_results(exp, name: str, out: Path, predictions: dict, targets, train_counts) -> None:
    metrics, per_class = [], []
    for (seed, arm), pred in predictions.items():
        measures, support, correct, accuracy = classification_metrics(pred, targets, train_counts)
        epoch = exp.protocol["stage1" if arm == STAGE1 else "stage2"]["epochs"]
        metrics.append({"dataset": name, "seed": seed, "arm": arm, "epoch": epoch, "test_rows": len(targets), **measures})
        for label, count in enumerate(train_counts):
            group = "Many" if count > 100 else "Few" if count < 20 else "Medium"
            per_class.append({"dataset": name, "seed": seed, "arm": arm, "class_id": label,
                              "train_count": count, "group": group, "test_support": support[label],
                              "correct": correct[label], "accuracy": accuracy[label]})
        with (out / f"{name}_seed{seed}_{arm}_predictions.npz").open("xb") as handle:
            np.savez_compressed(handle, predictions=pred, labels=targets)
    write_csv(out / f"{DISPLAY[name]}_metrics.csv", metrics)
    write_csv(out / "per_class_accuracy.csv", per_class)


def execute(name: str, output: Path, metadata_dir: Path) -> None:
    if OUTPUT_ROOT != TRAINED_RUN:
        raise RuntimeError(f"Set CCSAM_CROSS_DATASET_ATTEMPT to {TRAINED_RUN.name}")
    out = output / name
    if out.exists():
        raise FileExistsError(f"Refusing to overwrite evaluation: {out}")
    proof = checked_metadata(metadata_dir)
    if name == "places_lt":
        require_complete(output / "imagenet_lt", phase=PHASE, expected={
            "dataset": "imagenet_lt", "rows_scored": TEST_ROWS, "mapping_sha256": proof["mapping_sha256"],
            "original_artifacts_preserved": True,
        })

    exp = load_experiment(None)
    prepared = load_prepared(exp)
    manifest_shas = accepted_audit()["run_verification"]["input_integrity"]["after"]["manifest_hashes"]
    train_manifest = TRAIN_MANIFESTS[name]
    if sha256_file(train_manifest) != manifest_shas[train_manifest.name]:
        raise RuntimeError(f"Accepted TRAIN manifest SHA256 mismatch: {train_manifest}")
    all_models, provenance = verify_all_checkpoints(exp, prepared)
    artifacts = original_artifacts(provenance)
    verify_original_bytes(artifacts)
    device = cuda_device()

    config = exp.config(PHASE, dataset=name, trained_run=str(TRAINED_RUN), evaluation_root=str(output),
                        metadata_report_sha256=sha256_file(metadata_dir / "reconciliation.json"),
                        evaluation_source_sha256=sha256_file(Path(__file__)), environment=environment())
    with record_run(out, config, device=device) as status:
        status.update(dataset=name, rows_scored=0, stage1_verified=len(provenance),
                      stage2_verified=sum(len(item["stage2"]) for item in provenance.values()),
                      feature_caches_verified=len(provenance), original_artifacts_verified_before=True,
                      original_artifacts_preserved=False)
        write_json(out / "checkpoint_reuse.json", {
            "trained_run": str(TRAINED_RUN), "archived_artifact_index_sha256": sha256_file(PUBLISHED_INDEX),
            "dataset": name, "evaluated_seeds": exp.seeds, "stage1_epoch": exp.protocol["stage1"]["epochs"],
            "stage2_epoch": exp.protocol["stage2"]["epochs"], "matched_training_and_failure_artifacts": artifacts,
        })

        def mark_access():
            status.update(official_test_access=True, opened_at=now(),
                          official_test_manifest_sha256=manifest_shas[f"{DISPLAY[name]}_test.txt"])
            save_status(out, status)

        if name == "imagenet_lt":
            context = reconciled_imagenet_dataset(exp, proof, manifest_shas, mark_access)
            status["mapping_sha256"] = proof["mapping_sha256"]
        else:
            context = official_test_dataset(exp, name, manifest_shas, mark_access)
        with context as (dataset, targets):
            status["test_targets_sha256"] = array_sha256(targets)
            if name == "places_lt":
                status["places_class_folders_sha256"] = json_sha256(dataset.class_folders)
                status["places_class_folders"] = len(dataset.class_folders)
                status["places_distinct_test_paths"] = len(set(dataset.paths))
            run_log(out, f"{name}: official TEST identity check passed for {len(targets):,} rows")
            predictions = inference(exp, name, all_models[name], dataset, targets, device, out, status)
            status["rows_scored"] = len(targets)
            save_status(out, status)
        verify_model_states(all_models[name], provenance, name)
        verify_original_bytes(artifacts)
        status.update(original_artifacts_preserved=True, encoder_and_classifier_states_preserved=True)
        counts = np.asarray(prepared["datasets"][name]["train_class_counts"], dtype=np.int64)
        write_results(exp, name, out, predictions, targets, counts)
        run_log(out, f"{name}: saved fixed-checkpoint metrics for {len(predictions)} models")


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--dataset", required=True, choices=("imagenet_lt", "places_lt"))
    parser.add_argument("--metadata-dir", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    args = parser.parse_args()
    output, metadata = args.output_dir.resolve(), args.metadata_dir.resolve()
    if output.parent != RUNS or output == TRAINED_RUN:
        parser.error("evaluation output must be a separate subdirectory of the experiment's runs directory")
    if not metadata.is_relative_to(Path(__file__).resolve().parent):
        parser.error("metadata directory must be inside the reconciliation directory")
    execute(args.dataset, output, metadata)


if __name__ == "__main__":
    main()
